const KEY_SET = new Set(ICON_KEYS.map((i) => i.key));

export const hasIcon = (key: string | null | undefined): key is string =>
  !!key && KEY_SET.has(key);

/** The icon a category shows: the admin choice, else its own, else its parent's, else Other. */
export const effectiveIconKey = (
  category: { id: string; iconKey?: string | null; parentId?: string | null },
): string => {
  if (hasIcon(category.iconKey)) return category.iconKey;
  if (hasIcon(category.id)) return category.id;
  if (hasIcon(category.parentId)) return category.parentId;
  return "other";
};
